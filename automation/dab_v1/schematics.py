"""Native KiCad projects of the DAB-V1 boards: libraries, hierarchical schematics, rules, design records, ERC.

Reuses the generic pipeline: project_footprints.prepare_libraries (official footprints copied, AIPE footprints and
envelope models written), project_schematic.generate_project (wired presentation), rules.build_rules (net classes
and .kicad_dru from the insulation table) and run_check for native ERC.  Writes design/circuit_<board>.json,
groups, spacing evidence, library summary and the model BOM.  A generated project has no CAD evidence until ERC
has run; the summary returned by ``generate`` says whether it did.
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

from automation.dab_v1 import footprints as fpt, model, requirements as rq, rules
from automation.kicad_tools import project_footprints as pf, project_schematic as ps
from automation.kicad_tools.run_check import run_check
from automation.setup.detect_kicad import find_kicad_cli

PRESENTATION = dict(style='wired', exclude_supply=['SW5'], max_row_mm=250)


def board_dir(req, board: str) -> Path:
    return rq.EXAMPLE / board


def project_name(req, board: str) -> str:
    return req.board(board)['name']


def write_records(req, board: str, circuit, result: dict, built: dict, libraries: dict) -> None:
    design = rq.DESIGN
    design.mkdir(parents=True, exist_ok=True)
    (design / f'circuit_{board}.json').write_text(json.dumps(circuit.parts, indent=2) + '\n', encoding='utf-8')
    (design / f'groups_{board}.json').write_text(json.dumps({'groups': circuit.groups, 'titles': circuit.block_titles}, indent=2) + '\n', encoding='utf-8')
    (design / f'spacing_{board}.json').write_text(json.dumps(built['evidence'], indent=2) + '\n', encoding='utf-8')
    (design / f'library_{board}.json').write_text(json.dumps(libraries, indent=2) + '\n', encoding='utf-8')
    (design / f'schematic_summary_{board}.json').write_text(json.dumps({k: v for k, v in result.items() if k != 'files'}, indent=2, default=str) + '\n', encoding='utf-8')
    components = rq.EXAMPLE / 'components'
    components.mkdir(exist_ok=True)
    with (components / f'bom_{board}.csv').open('w', newline='', encoding='utf-8') as handle:
        keys = ['board', 'ref', 'value', 'mpn', 'maker', 'footprint', 'source', 'dnp', 'note']
        writer = csv.DictWriter(handle, keys)
        writer.writeheader()
        for p in circuit.parts:
            if not p.get('in_bom', p['kind'] not in ('TP', 'H')):
                continue
            writer.writerow({k: p.get(k, '') for k in keys})


def generate(req, board: str, *, erc: bool = False) -> dict:
    circuit = model.build(req, board)
    parts = circuit.parts
    flags = model.flag_nets(circuit)
    report = ps.analyse_connectivity(parts, flags)
    problems = {k: report[k] for k in ('undriven_power_nets', 'pin_conflicts', 'single_pin_nets', 'no_connect_pins_with_nets') if report[k]}
    if problems:
        raise ValueError(f'{board}: model connectivity pre-check failed: {json.dumps(problems, default=str)[:2000]}')
    out = board_dir(req, board)
    out.mkdir(parents=True, exist_ok=True)
    used = {p['footprint'] for p in parts}
    custom = {k: v for k, v in fpt.custom(req.components).items() if 'AIPE:' + k in used}
    libraries = pf.prepare_libraries(parts, out, custom_footprints=custom,
                                     notice_text='Generated by automation.dab_v1.schematics through project_footprints.prepare_libraries. Official '
                                                 'footprints keep the KiCad library licence; AIPE isolation footprints (8 mm land gap), film-capacitor and '
                                                 'heat-sink envelopes are dimensioned from the requirement files and need review against the manufacturer drawings.')
    built = rules.build_rules(req, board, parts)
    cfg = req.board(board)
    presentation = dict(PRESENTATION, groups=circuit.groups, group_titles=circuit.block_titles,
                        include_supply=['BUS_P', 'BUS_N', 'S_5V', 'S_16V'] if cfg['side'] != 'control' else ['REF3', '5V0'])
    pages = model.CONTROL_PAGES if board == 'control' else model.POWER_PAGES
    design_rules = dict(min_clearance=cfg['min_clearance_mm'], min_track_width=cfg['min_track_mm'], min_via_diameter=cfg['via_mm'][0],
                        min_through_hole_diameter=cfg['via_mm'][1], min_hole_clearance=cfg['min_hole_clearance_mm'], min_copper_edge_clearance=0.5)
    spec = ps.ProjectSpec(name=project_name(req, board), title=cfg['title'], kicad_dir=out, design_dir=rq.DESIGN, pages=pages, parts=parts,
                          revision=rq.GENERATION, board=board, comment=rq.BANNER, flag_nets=flags, flag_page='07_interface',
                          net_classes=built['classes'], dru_text=built['dru'], design_rules=design_rules,
                          mapping_name=f'schematic_mapping_{board}.json', presentation=presentation,
                          header_lines=[f'{req.specification["project"]}; generation {rq.GENERATION}.',
                                        'Requirement files: examples/dab-10kw/requirements; insulation table values are reference inputs to be reviewed.',
                                        'No fabrication, energisation or procurement is authorised by this schematic.'])
    result = ps.generate_project(spec)
    write_records(req, board, circuit, result, built, libraries)
    summary = dict(board=board, project=project_name(req, board), parts=len(parts), sheets=[s['key'] for s in result['sheets']],
                   symbol_fallbacks=result['symbol_fallbacks'], flags=flags, library=libraries['libraries'], custom_footprints=sorted(custom),
                   erc=None)
    if erc:
        code, manifest = run_check('erc', out / f'{project_name(req, board)}.kicad_sch', rq.VERIFICATION / 'erc', cli=find_kicad_cli())
        data = json.loads(Path(manifest).read_text(encoding='utf-8'))
        summary['erc'] = dict(exit_code=code, manifest=str(manifest), finding_count=data.get('finding_count'), status=data.get('status'))
    (rq.DESIGN / f'schematic_summary_{board}.json').write_text(json.dumps(summary, indent=2, default=str) + '\n', encoding='utf-8')
    return summary


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--board', choices=(*rq.BOARDS, 'all'), default='all')
    parser.add_argument('--erc', action='store_true', help='run kicad-cli ERC and record the manifest under verification/erc')
    args = parser.parse_args(argv)
    req = rq.load()
    worst = 0
    for board in rq.BOARDS if args.board == 'all' else (args.board,):
        summary = generate(req, board, erc=args.erc)
        print(json.dumps(summary, indent=2, default=str), flush=True)
        if summary['erc'] and summary['erc']['exit_code']:
            worst = max(worst, summary['erc']['exit_code'])
    return worst


if __name__ == '__main__':
    raise SystemExit(main())
