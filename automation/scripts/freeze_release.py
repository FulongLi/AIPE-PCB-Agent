"""Create a non-overwritable release snapshot of the SiC buck example with a SHA-256 manifest and a portable archive.

Generalisation of freeze_v2.py for later generations (V2.1, ...). The two-board verification
(automation/scripts/verify_sic_buck.py) runs first and the freeze is refused when it fails. The
snapshot copies the engineering inputs, design records, component data, KiCad sources,
manufacturing exports, review package and verification evidence; full-length simulation
waveforms are excluded (regenerable). A frozen directory must never be edited afterwards and an
existing snapshot is never overwritten.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
from datetime import datetime, timezone
from pathlib import Path

from automation.scripts import verify_sic_buck

FOLDERS = ("input", "design", "components", "kicad", "manufacturing", "review", "verification")
IGNORE = shutil.ignore_patterns("*.kicad_prl", "*-backups", "*.lck")

RELEASES = {
    "v2": dict(
        label="AI-GENERATED ENGINEERING PROTOTYPE V2 - HUMAN REVIEW REQUIRED",
        title="Frozen V2 engineering review prototype",
        notes="",
    ),
    "v2.1": dict(
        label="AI-GENERATED ENGINEERING PROTOTYPE V2.1 - HUMAN REVIEW REQUIRED",
        title="Frozen V2.1 engineering review prototype",
        notes=(
            "V2.1 keeps the V2 electrical design (topology, components, operating specification, two-board\n"
            "architecture) and changes the presentation: schematics drawn with wires, junctions, power symbols\n"
            "and hierarchical labels in functional groups, and boards routed with the upgraded grid router\n"
            "(octilinear simplification and tangent arcs; 8-direction search where it converges). The netlist\n"
            "is identical to V2 by construction and checked by the generator gates. The V2 vs V2.1 comparison\n"
            "is review/v2_v21_comparison.md; routing-quality and schematic-readability metrics are under\n"
            "verification/engineering_checks/. Open engineering issues carried over from V2 remain listed in\n"
            "verification/known_issues.md.\n"
        ),
    ),
}


def readme(version: str) -> str:
    cfg = RELEASES[version]
    notes = ("\n" + cfg["notes"]) if cfg["notes"] else ""
    return f"""# {cfg['title']}

{cfg['label']}

400 V (360-440 V) to 200 V, 5 kW, 50 kHz SiC synchronous buck: power board and
TMS320F28335 control board designed with the AIPE Engineering Knowledge System.
{notes}
Start with review/design_report.md, review/knowledge_utilisation_report.md and the
schematic/layout PDFs in review/. Read verification/known_issues.md before any
physical work. KiCad sources and exported manufacturing formats are included, but no
fabrication, purchase or energisation is authorised; the design remains subject to
independent human engineering review.

This snapshot must not be overwritten. Future reviewed changes belong in a later
generation. SHA256SUMS.json covers every file except itself. Absolute paths inside
native command logs describe the original host and are historical evidence.
simulation/results contains per-run summaries, decks and plots; full waveform CSV files
are regenerated by simulation/results/run_campaign.py.
"""


def freeze(version: str, example: Path | None = None) -> dict:
    """Verify, copy the snapshot to releases/<version>, write the manifest and the zip; return a summary dict."""
    if version not in RELEASES:
        raise SystemExit(f"unknown release {version!r}; known: {', '.join(RELEASES)}")
    example = example or verify_sic_buck.EXAMPLE
    evidence = verify_sic_buck.verify()
    if evidence["status"] != "passed":
        raise SystemExit("verification failed; refusing to freeze: " + "; ".join(evidence["problems"]))
    target = example / "releases" / version
    target.mkdir(parents=True, exist_ok=False)  # never overwrite a frozen snapshot
    for folder in FOLDERS:
        shutil.copytree(example / folder, target / folder, ignore=IGNORE)
    shutil.copytree(example / "simulation", target / "simulation", ignore=shutil.ignore_patterns("waveforms.csv"))
    (target / "README.md").write_text(readme(version), encoding="utf-8")
    manifest = dict(release=version, label=RELEASES[version]["label"], created_utc=datetime.now(timezone.utc).isoformat(),
                    source_commit=subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip(),
                    status="frozen CAD and engineering review prototype; hardware unqualified", files={})
    for path in sorted(target.rglob("*")):
        if path.is_file():
            manifest["files"][path.relative_to(target).as_posix()] = {"bytes": path.stat().st_size, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
    (target / "SHA256SUMS.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    for name, data in manifest["files"].items():
        assert hashlib.sha256((target / name).read_bytes()).hexdigest() == data["sha256"], name
    archive = shutil.make_archive(str(target.parent / f"{version}-review-package"), "zip", root_dir=target)
    return dict(frozen_files=len(manifest["files"]), path=str(target), archive=archive, source_commit=manifest["source_commit"], label=manifest["label"])


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description="Freeze a release snapshot of the SiC buck example (refuses when verification fails or the snapshot exists).")
    parser.add_argument("--version", default="v2.1", choices=sorted(RELEASES))
    args = parser.parse_args(argv)
    print(json.dumps(freeze(args.version)))


if __name__ == "__main__":
    main()
