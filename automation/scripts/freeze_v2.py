"""Create the non-overwritable V2 snapshot with a SHA-256 manifest and a portable archive.

Runs the two-board verification first (automation/scripts/verify_sic_buck.py) and refuses
to freeze when it fails. The snapshot copies the engineering inputs, design records,
component data, KiCad sources, manufacturing exports, review package and verification
evidence. Full-length simulation waveforms are excluded (regenerable); their summaries
are included. Like V1, the frozen directory must never be edited afterwards.
"""
from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
from datetime import datetime, timezone
from pathlib import Path

from automation.scripts.verify_sic_buck import EXAMPLE, verify

LABEL = "AI-GENERATED ENGINEERING PROTOTYPE V2 - HUMAN REVIEW REQUIRED"
README = f"""# Frozen V2 engineering review prototype

{LABEL}

400 V (360-440 V) to 200 V, 5 kW, 50 kHz SiC synchronous buck: power board and
TMS320F28335 control board designed with the AIPE Engineering Knowledge System.

Start with review/design_report.md, review/knowledge_utilisation_report.md and the
schematic/layout PDFs in review/. Read verification/known_issues.md before any
physical work. KiCad sources and exported manufacturing formats are included, but no
fabrication, purchase or energisation is authorised; the design remains subject to
independent human engineering review.

This snapshot must not be overwritten. Future reviewed changes belong in a later
generation. SHA256SUMS.json covers every file except itself. Absolute paths inside
native command logs describe the original host and are historical evidence.
simulation/results contains per-run summaries, decks and plots; full waveform CSV files
are regenerated by simulation/results/run_campaign.py.
"""


def main() -> None:
    evidence = verify()
    if evidence["status"] != "passed":
        raise SystemExit("verification failed; refusing to freeze: " + "; ".join(evidence["problems"]))
    target = EXAMPLE / "releases/v2"
    target.mkdir(parents=True, exist_ok=False)
    for folder in ("input", "design", "components", "kicad", "manufacturing", "review", "verification"):
        shutil.copytree(EXAMPLE / folder, target / folder, ignore=shutil.ignore_patterns("*.kicad_prl", "*-backups", "*.lck"))
    shutil.copytree(EXAMPLE / "simulation", target / "simulation", ignore=shutil.ignore_patterns("waveforms.csv"))
    (target / "README.md").write_text(README, encoding="utf-8")
    manifest = dict(release="v2", label=LABEL, created_utc=datetime.now(timezone.utc).isoformat(),
                    source_commit=subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip(),
                    status="frozen CAD and engineering review prototype; hardware unqualified", files={})
    for path in sorted(target.rglob("*")):
        if path.is_file():
            manifest["files"][path.relative_to(target).as_posix()] = {"bytes": path.stat().st_size, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
    (target / "SHA256SUMS.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    for name, data in manifest["files"].items():
        assert hashlib.sha256((target / name).read_bytes()).hexdigest() == data["sha256"], name
    archive = shutil.make_archive(str(target.parent / "v2-review-package"), "zip", root_dir=target)
    print(json.dumps(dict(frozen_files=len(manifest["files"]), path=str(target), archive=archive, source_commit=manifest["source_commit"])))


if __name__ == "__main__":
    main()
